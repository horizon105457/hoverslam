// Run a scenario headless and write public/sims/<name>.bin.gz for instant playback in the app.
import fs from 'fs';
import zlib from 'zlib';
import { loadCarNode } from './load-car-node.mjs';
import { CrashSim } from '../src/sim/solver.js';
import { RecordingEncoder, finalMeta, packRecording } from '../src/sim/recording.js';
import { PRESETS } from '../src/scene/layout.js';
const args = Object.fromEntries(process.argv.slice(2).map(a => a.split('=')));
const name = args.preset || 'roof';
const car = await loadCarNode({ h: 0.065 });
const settledBuf = fs.readFileSync(new URL('../public/assets/settled.bin', import.meta.url));
const head = new Uint32Array(settledBuf.buffer.slice(settledBuf.byteOffset, settledBuf.byteOffset + 8));
if (head[0] !== car.nodes.count || head[1] !== car.beams.count) throw new Error('settled.bin is stale: run tools/build-settle.mjs');
const settled = new Float32Array(settledBuf.buffer.slice(settledBuf.byteOffset + 8, settledBuf.byteOffset + settledBuf.length));
const sc = { ...PRESETS[name], ...(args.speed ? { speed: +args.speed } : {}), strength: +(args.s || PRESETS[name].strength || 1), joints: +(args.j || PRESETS[name].joints || 1), recordHz: +(args.hz || 120), duration: +(args.dur || 7) };
const sim = new CrashSim(car, sc);
sim.setup(settled);
const enc = new RecordingEncoder(car);
const frames = [];
let k = 0;
const t0 = Date.now();
frames.push(enc.encode(sim, true));
sim.run(sc.duration, s => { k++; frames.push(enc.encode(s, k % 4 === 0)); if (k % 60 === 0) process.stdout.write(`\r${name} t=${s.time.toFixed(2)} ${((Date.now() - t0) / 1000).toFixed(0)}s`); });
const meta = finalMeta(sim, enc, { name, label: PRESETS[name].label });
const raw = packRecording(meta, frames);
const gz = zlib.gzipSync(Buffer.from(raw), { level: 6 });
fs.mkdirSync(new URL('../public/sims/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL(`../public/sims/${name}.sim`, import.meta.url), gz);
console.log(`\n${name}: ${frames.length} frames raw ${(raw.byteLength / 1e6).toFixed(1)}MB gz ${(gz.length / 1e6).toFixed(1)}MB in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
console.log('detached', sim.events.breaks.filter(e => e.type === 'detach').map(e => e.piece + '@' + e.t.toFixed(2)).join(' '));
